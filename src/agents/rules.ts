export function buildCorrectionPrompt(kind: TurnKind): string {
	const tool = expectedTool(kind);
	return `[法官] 你还没有提交本回合的有效行动。请立即调用工具 \`${tool}\` 完成行动。只输出文字不算行动；如果之前的工具调用被拒绝，请根据拒绝原因修正参数。`;
}

export function expectedTool(kind: TurnKind): string {
	switch (kind) {
		case "wolf_turn":
			return "wolf_vote";
		case "seer_check":
			return "seer_check";
		case "witch_act":
			return "witch_act";
		case "last_words":
			return "last_words";
		case "hunter_shoot":
			return "hunter_shoot";
		case "sheriff_signup":
			return "sheriff_run";
		case "sheriff_speech":
			return "sheriff_say";
		case "sheriff_vote":
			return "sheriff_vote";
		case "badge_transfer":
			return "transfer_badge";
		case "day_speech":
			return "say";
		case "day_vote":
			return "vote";
	}
}
