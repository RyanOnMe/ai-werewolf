/** 完整规则。既是系统提示的一部分，也通过 view_rules 工具按需返回。 */
export const RULES_TEXT = `# AI 狼人杀 · 9 人局规则

## 配置
3 名狼人、3 名村民、1 名预言家、1 名女巫、1 名猎人。没有警长、守卫、白痴等扩展角色；不存在警上竞选、警徽流、守卫守护等机制，请不要使用这些概念。

## 阵营与胜利
- 狼人阵营（3 狼）：杀光所有村民，或杀光所有神职（预言家、女巫、猎人），即获胜。
- 好人阵营（3 村民 + 3 神职）：放逐所有狼人即获胜。
- 如果同一次结算中狼人全灭、同时好人也被屠边，优先判好人胜（狼人必须至少存活一人才能获胜）。

## 夜晚流程
1. 狼人行动：存活的狼人按座位顺序在狼队频道发言，并投票选择刀杀目标；也可以选择空刀。狼队内部平票则空刀。允许自刀（刀狼队友）。
2. 预言家行动：查验一名存活玩家（不能是自己），得到“狼人”或“好人”。即使当夜被杀，也仍然完成查验。
3. 女巫行动：法官告知女巫当晚狼队刀杀的目标。女巫可以选择使用解药救该目标、使用毒药毒杀一名存活玩家（不能是自己），或不用药。
   - 解药和毒药各只有一次。
   - 同一晚不能同时使用解药和毒药。
   - 第一夜之后不能自救。
   - 即使女巫当夜被杀，她仍然可以完成用药。
4. 天亮结算：狼刀目标（若未被救）和毒药目标死亡。死亡公告只公布座位，不公布死因。

## 白天流程
1. 公布夜晚死亡；若有死者，死者依次留遗言。
2. 猎人若死于狼刀或被放逐，可以在遗言后开枪带走一名存活玩家，也可以放弃；被毒杀时不能开枪。
3. 存活玩家按顺序依次公开发言，每人一次。
4. 全体存活玩家投票放逐：可以投给任意存活的其他玩家，也可以弃票；不能投自己。
5. 得票最多且唯一者被放逐；最高票平票则无人被放逐。被放逐者留遗言；若被放逐者是猎人，可以开枪。
6. 进入下一夜。

## 角色说明
- 狼人：知道所有狼队友；夜里与队友讨论并投票刀人；白天要伪装成好人。可以自刀。
- 村民：没有夜间技能，靠听发言、分析投票和表达立场。
- 预言家：每晚查验一名存活玩家的阵营（狼人/好人），不能验自己；被刀当夜仍可查验。查验结果只属于你。
- 女巫：有解药和毒药各一次；知道当晚狼刀目标；不能同晚双药；第一夜之后不能自救；被刀当夜仍可用药。
- 猎人：被狼人杀害或被投票放逐时，出局后可以开枪带走一名存活玩家；被女巫毒杀时不能开枪；可以放弃开枪。

## 信息与发言
- 夜间行动、狼队讨论、查验结果、女巫用药都是私密信息。
- 死亡公告不公布死因；只有猎人开枪是公开事件。
- 遗言公开。游戏结束时公布所有身份。
- 每个白天每人一次公开发言，最多 500 字；遗言最多 500 字。
- 发言可以欺骗、伪装、误导；这是游戏的一部分。

## 其他
- 出局玩家不再发言、投票或使用夜间技能，只有遗言和猎人开枪。
- 夜晚同时结算：当夜被杀的神职仍然完成自己的夜间行动。
- 游戏在第 30 天仍无胜负时中止（正常对局不会发生）。`;

